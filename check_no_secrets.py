#!/usr/bin/env python3
"""Fail if credentials or internal host paths would enter the repository.

Agent trajectories dumped by mini-swe-agent embed the LLM ``api_key`` and the
Docker bind-mount host path, so they must never be committed. GitHub's own push
protection only recognizes well-known provider formats and does not catch keys
issued by third-party inference proxies, which is why this check exists.

Usage:
    python3 check_no_secrets.py            # scan all tracked files
    python3 check_no_secrets.py --staged   # scan staged content (git hook)
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys

# Benchmark data that legitimately looks like a credential. The cc-filter task
# evaluates secret redaction, so its fuzz fixtures must contain decoy tokens.
# These are generated by FuzzHelper.get_string() and are not real credentials.
ALLOWLIST = {
    "xoxb-nyFF1nDy4VPv7kQ7tPsBRxLncxC6Rf1VJiyKJ2Yrypof-h-Rnu",
}

PATTERNS = {
    "LLM api_key field": re.compile(rb'"api_key"\s*:\s*"(?!<REDACTED>)[^"]{8,}"'),
    "internal host path": re.compile(rb"/data00/home/[a-zA-Z0-9._-]+"),
    "OpenAI-style key": re.compile(rb"sk-(?:ant-|proj-|cp-)?[A-Za-z0-9_-]{20,}"),
    "GitHub token": re.compile(rb"gh[pousr]_[A-Za-z0-9]{36}|github_pat_[A-Za-z0-9_]{50,}"),
    "AWS access key": re.compile(rb"AKIA[0-9A-Z]{16}"),
    "Slack token": re.compile(rb"xox[baprs]-[A-Za-z0-9-]{20,}"),
    "GitLab token": re.compile(rb"glpat-[A-Za-z0-9_-]{20,}"),
    "private key block": re.compile(rb"-----BEGIN [A-Z ]*PRIVATE KEY-----"),
}


def git(*args: str) -> str:
    return subprocess.run(
        ["git", *args], capture_output=True, text=True, check=True
    ).stdout


def iter_files(staged: bool):
    """Yield (path, content_bytes) for the files to inspect."""
    if staged:
        names = git("diff", "--cached", "--name-only", "--diff-filter=ACMR").split("\n")
    else:
        names = git("ls-files").split("\n")

    for name in filter(None, names):
        try:
            if staged:
                blob = subprocess.run(
                    ["git", "show", f":{name}"], capture_output=True, check=True
                ).stdout
            else:
                with open(name, "rb") as handle:
                    blob = handle.read()
        except (subprocess.CalledProcessError, OSError):
            continue
        yield name, blob


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--staged", action="store_true", help="scan staged content only")
    args = parser.parse_args()

    findings: list[tuple[str, str, str]] = []
    for name, blob in iter_files(args.staged):
        for label, pattern in PATTERNS.items():
            for match in pattern.findall(blob):
                text = match.decode("utf-8", "replace")
                if text in ALLOWLIST:
                    continue
                findings.append((name, label, text))

    if not findings:
        print("No credentials or internal host paths found.")
        return 0

    print(f"BLOCKED: found {len(findings)} potential secret(s):\n", file=sys.stderr)
    for name, label, text in findings[:40]:
        preview = text if len(text) <= 24 else text[:16] + "..." + text[-4:]
        print(f"  {name}: {label} -> {preview}", file=sys.stderr)
    if len(findings) > 40:
        print(f"  ... and {len(findings) - 40} more", file=sys.stderr)
    print(
        "\nIf these are agent trajectories, run:\n"
        "    python3 sanitize_trajectories.py <results-dir>\n"
        "If a match is benchmark fuzz data, add it to ALLOWLIST in this script.",
        file=sys.stderr,
    )
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
